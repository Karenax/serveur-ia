'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const {directory}=require('./test_artifacts.cjs');
module.exports=async({page,state,errors,until,sleep,voiceUI})=>{
 await page.evaluate(()=>clientState());
 assert.equal(await page.locator('#account-status').textContent(),'Accès personnel · Linux');
 assert.equal(await page.locator('#voice-start').count(),1);
 assert.equal(await page.locator('#ui-theme option[value="system"]').textContent(),'Comme le système');
 await page.evaluate(()=>showView('updates'));
 assert.equal(await page.locator('#update-apply').isVisible(),false);
 assert((await page.locator('[data-view="updates"]').innerText()).includes('nouveau paquet Linux'));
 await page.evaluate(()=>showView('connection'));
 const connection=await page.locator('[data-view="connection"]').innerText();
 assert(connection.includes('Cloudflare peut techniquement lire'));assert(!connection.includes('EXE'));
 await page.evaluate(()=>showView('chat'));
 await page.locator('#prompt').fill('Brouillon Linux à conserver');
 await page.evaluate(()=>uiPersistPreferences());
 assert(Object.values(state.preferences.conversation_drafts).includes('Brouillon Linux à conserver'));
 await page.locator('#prompt').fill('');await page.evaluate(()=>uiPersistPreferences());
 await voiceUI.click('[data-view-button="voice"]');
 await voiceUI.click('#conversation-start');await page.waitForFunction(()=>window.conversationBusy);
 assert.equal(state.native.quality,'low');
 state.native.speech_id=1;state.native.turns=[{id:1,speech_id:1,text:'Bonjour Kiara, réponds-moi.'}];
 await until(()=>state.chats.length===1&&state.speech.length>0,'Linux utterance and server speech');
 await page.waitForFunction(()=>window.__audio.started>0);
 await until(()=>state.native.playback_paused===true,'capture paused during response');
 await page.waitForFunction(()=>!busy&&!historySyncPending&&window.__audio.ended===window.__audio.started);
 await until(()=>state.native.playback_paused===false&&!state.native.microphone_closed,'microphone resumes after playback');
 assert.equal(state.stops,0);assert.deepEqual(state.acks,[1]);
 await voiceUI.click('#conversation-mute');await until(()=>state.native.muted,'mute');
 const before=state.chats.length;
 state.native.speech_id=2;state.native.turns=[{id:2,speech_id:2,text:'Ne pas transmettre pendant la coupure du micro.'}];
 await sleep(350);assert.equal(state.chats.length,before);
 state.native.turns=[];
 await voiceUI.click('#conversation-mute');await until(()=>!state.native.muted,'unmute');
 await voiceUI.click('#conversation-start');await page.waitForFunction(()=>!window.conversationBusy);
 await voiceUI.selectOption('#voice-quality','max');
 assert.equal(await page.locator('#voice-execution').inputValue(),'server');
 assert.equal(await page.locator('#voice-execution option[value="pc"]').isDisabled(),true);
 assert.equal(await page.locator('#conversation-interruptions').isDisabled(),true);
 assert.equal(await page.locator('#voice-gpu-options').isVisible(),false);
 assert.equal(await page.locator('#voice-image-capture').isVisible(),false);
 assert(!(await page.locator('#voice-settings-dialog').innerText()).includes('réglages Windows'));
 state.native.max_tools_installed=true;
 await voiceUI.click('#conversation-start');await page.waitForFunction(()=>window.conversationBusy);
 assert.equal(state.native.quality,'max');assert.equal(state.native.execution,'server');
 state.native.speech_id=1;state.native.turns=[{id:1,speech_id:1,text:'Une question avec le vocal Max du serveur.'}];
 await until(()=>state.chats.length===2,'Max server turn');
 await page.waitForFunction(()=>!busy&&!historySyncPending&&window.__audio.ended===window.__audio.started);
 await until(()=>state.native.playback_paused===false,'Max playback completes');
 await page.screenshot({path:path.join(directory('linux'),'vocal.png'),fullPage:true});
 await voiceUI.click('#conversation-start');await page.waitForFunction(()=>!window.conversationBusy);
 assert(state.native.microphone_closed);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({platform:'linux',passed:true,simulation:'Synthetic recognition and PCM; no Linux microphone',
  checks:['saved draft','manual updates','Low voice turn','server PCM playback','playback pause/resume','mute/unmute','Max on server','hangup closes capture','no JS errors']}));
};
